def issue(code, level='error', fix=None, **args):
    """Build one issue (a JSON-serializable dict)."""
    rule, english, arabic = MESSAGES[code]
    return {
        'code': code,
        'rule': rule.format(**args) if rule else '',
        'level': level,
        'en': english.format(**args),
        'ar': arabic.format(**args),
        'fix': fix or {},
    }
